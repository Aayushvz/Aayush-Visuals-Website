/*
  Hand-drawn pixel glyphs for /test.

  Data only - nothing here renders. `#` is a filled cell, `.` is empty. Every
  row of a glyph must be the same length; that length is the glyph's advance
  width, so spacing is a property of the drawing rather than a number applied
  afterwards.

  Two sets, because the reference uses two very different sizes and a glyph
  drawn for one reads badly at the other. DISPLAY is the two-line wordmark,
  drawn on a 16-row body with lowercase sitting in the bottom 11. STICKER is
  the small rotated labels, on a 7-row body - small enough that curves have
  to be implied rather than drawn.

  The heavy outline around these letters is NOT in this file. It is computed
  from the filled cells at render time (see PixelText), so it can never fall
  out of sync with a letterform that gets nudged later.
*/

export type Glyph = string[];
export type GlyphSet = {
  rows: number;
  gap: number; // empty columns between glyphs
  space: number; // advance width of " "
  glyphs: Record<string, Glyph>;
};

