export const BOWLER_POSES = Object.keys(BOWLER_FRAMES) as BowlerPose[];

/** Kick off loading for one side. Safe to call repeatedly. */
export function preloadBowler(team: TeamKit) {
  preloadKit(team, "bowler", BOWLER_POSES);
}

/** A frame, or null while it is still loading — callers fall back to the
    procedural figure so the field is never empty on the first ball. */
export function bowlerFrame(team: TeamKit, pose: BowlerPose) {
  return kitFrame(team, "bowler", pose, BOWLER_FRAMES[pose]);
}

export function bowlerReady(team: TeamKit) {
  return kitReady(team, "bowler", BOWLER_POSES);
}
