/*
  Regenerates components/projects/imageDims.ts from whatever is currently in
  public/projects. Run after adding or replacing case-study artwork:

    node scripts/gen-image-dims.mjs

  The generated map lets the case-study pages put real width/height on every
  lazy <img>, which is what stops a section of a dozen frames from collapsing
  to nothing and then shoving the page down as each one decodes.
*/
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const ROOT = "public";
const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]
  );

const dims = {};
for (const file of walk(path.join(ROOT, "projects"))) {
  if (!/\.(webp|png|jpe?g)$/i.test(file)) continue;
  try {
    const m = await sharp(fs.readFileSync(file)).metadata();
    dims["/" + path.relative(ROOT, file).split(path.sep).join("/")] = [m.width, m.height];
  } catch {
    /* unreadable or not a raster — skip rather than fail the whole run */
  }
}

const body = Object.keys(dims)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: [${dims[k][0]}, ${dims[k][1]}],`)
  .join("\n");

fs.writeFileSync(
  "components/projects/imageDims.ts",
  `/*
  Generated by scripts/gen-image-dims.mjs — do not edit by hand.

  Intrinsic pixel sizes for everything under public/projects, so the
  case-study pages can reserve the exact box for each lazy image before it
  loads. Without this a surface section with a dozen frames collapses to zero
  height and then shoves the page down as each one arrives.
*/
export const IMAGE_DIMS: Record<string, [number, number]> = {
${body}
};

export function dimsFor(src: string) {
  const d = IMAGE_DIMS[src];
  return d ? { width: d[0], height: d[1] } : {};
}
`
);

console.log(`wrote ${Object.keys(dims).length} entries`);
